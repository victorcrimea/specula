//! The terrain resource, format v1, served once per match at
//! `/terrain/<id>`. Little-endian:
//!
//! u8 version, u32 tiles per side n, f32 water level (m), f32 shallow water
//! depth (m), u8 circular, u32 palette count, count x {u32 0xRRGGBB, u16
//! name length, UTF-8 name}, (n+1)^2 x u16 heights (1/92 m), n^2 x u16
//! palette index (0xFFFF: none), n^2 x u32 blend priority. Heights and
//! tiles are row-major, x fastest.
//!
//! The palette holds each texture's minimap base colour, so the client can
//! shade the tiles itself, as the engine's minimap does, and its name, by
//! which the 3D view finds the baked texture.

use std::collections::HashMap;
use std::collections::HashSet;
use std::hash::DefaultHasher;
use std::hash::Hash;
use std::hash::Hasher;
use std::sync::LazyLock;
use std::sync::Mutex;

use crate::feed::Terrain;
use crate::wire::Writer;

const VERSION: u8 = 1;
/// What the minimap shows for a tile without a known texture.
const UNKNOWN_COLOR: u32 = 0xFF_FF_FF;

/// Generated by `specula-tools`' terrain-colors from the game data, since
/// the nonvisual observer cannot compute texture colours itself.
static COLORS: LazyLock<HashMap<&'static str, u32>> = LazyLock::new(|| {
    include_str!("../data/terrain-colors.txt")
        .lines()
        .filter_map(|line| {
            let (name, color) = line.split_once(' ')?;
            Some((name, u32::from_str_radix(color, 16).ok()?))
        })
        .collect()
});

/// Names already reported, so a long-running server logs each once.
static REPORTED: LazyLock<Mutex<HashSet<String>>> = LazyLock::new(Default::default);

pub struct Resource {
    /// Never 0, which the keyframe uses for "no terrain".
    pub id: u64,
    pub bytes: Vec<u8>,
    pub unknown: usize,
}

pub fn encode(terrain: &Terrain) -> Resource {
    let mut unknown = 0;
    let palette: Vec<u32> = terrain
        .textures
        .iter()
        .map(|name| {
            COLORS.get(name.as_str()).copied().unwrap_or_else(|| {
                unknown += 1;
                if REPORTED.lock().unwrap().insert(name.clone()) {
                    eprintln!("terrain texture {name} is not in the colour table");
                }
                UNKNOWN_COLOR
            })
        })
        .collect();

    let mut out = Writer::default();
    out.u8(VERSION);
    out.u32(terrain.tiles_per_side);
    out.f32(terrain.water_level as f32 / 65536.0);
    out.f32(terrain.shallow_depth);
    out.u8(u8::from(terrain.circular));
    out.u32(palette.len() as u32);
    for (color, name) in palette.iter().zip(&terrain.textures) {
        out.u32(*color);
        out.u16(name.len() as u16);
        out.0.extend_from_slice(name.as_bytes());
    }
    for height in &terrain.heights {
        out.u16(*height);
    }
    for tile in &terrain.tiles {
        out.u16(*tile);
    }
    for priority in &terrain.priorities {
        out.u32(*priority);
    }

    // Only this process serves the id, so a hash that is not stable across
    // Rust versions is fine; content-derived ids let browsers cache forever.
    let mut hasher = DefaultHasher::new();
    out.0.hash(&mut hasher);
    Resource {
        id: hasher.finish().max(1),
        bytes: out.0,
        unknown,
    }
}
